#!/usr/bin/env python3
"""Regenerate lib/ui/icons.dart from the icons the code uses.

The phosphor_flutter package can't be a dependency (it subclasses IconData,
which Flutter now forbids), so the app bundles the Phosphor fonts and this
script emits `const IconData` constants for every `PhosphorIcons<Style>.<name>`
referenced under lib/. Code points come from the phosphor_flutter 2.1.0
source, fetched once into the pub cache:

    dart pub cache add phosphor_flutter --version 2.1.0
    python3 tool/gen_icons.py
"""
import glob
import os
import re
import sys

SRC = os.path.expanduser('~/.pub-cache/hosted/pub.dev/phosphor_flutter-2.1.0/lib/src/')
if not os.path.isdir(SRC):
    sys.exit('phosphor_flutter 2.1.0 is not in the pub cache — see the docstring.')

used = {}
for f in glob.glob('lib/**/*.dart', recursive=True):
    if f.endswith('ui/icons.dart'):
        continue
    for style, name in re.findall(r'PhosphorIcons(Regular|Bold|Fill)\.(\w+)', open(f).read()):
        used.setdefault(style, set()).add(name)

out = [
    '// GENERATED by tool/gen_icons.py — do not edit by hand.',
    '// Phosphor icons (MIT, assets/fonts/PHOSPHOR_LICENSE) as plain IconData.',
    'library;',
    '',
    "import 'package:flutter/widgets.dart';",
    '',
]
missing = []
for style in ['Regular', 'Bold', 'Fill']:
    src = open(f'{SRC}phosphor_icons_{style.lower()}.dart').read()
    cps = dict(re.findall(r'static const (\w+) = PhosphorFlatIconData\((0x[0-9a-f]+)', src))
    out += [f'class PhosphorIcons{style} {{', f'  const PhosphorIcons{style}._();']
    for name in sorted(used.get(style, [])):
        if name not in cps:
            missing.append(f'{style}.{name}')
            continue
        out.append(f"  static const IconData {name} = IconData({cps[name]}, fontFamily: 'Phosphor{style}', matchTextDirection: true);")
    out += ['}', '']
open('lib/ui/icons.dart', 'w').write('\n'.join(out))
print({k: len(v) for k, v in used.items()})
if missing:
    sys.exit('Unknown icons: ' + ', '.join(missing))
